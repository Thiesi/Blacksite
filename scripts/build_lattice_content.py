"""Author the eleven district sectors from world 03-lattice, section 2.

Layouts and edges are committed data, never generated by the live server.
Core hardware remains explicitly staged for S14/S25 rather than invented.
"""

import json
from pathlib import Path
import re

ROOT = Path("src/blacksite/content")
WORLD = Path("docs/world/03-lattice.md")
DISTRICTS = (
    ("spire","Spire","Lobby Register","Sump","hidden"),
    ("core","Core","Plaza Exchange","The Grate","gated"),
    ("vatside","Vatside","Wake Hall Node","Drain","hidden"),
    ("tramyard","Tramyard","Gate Bus East","Sidings","gated"),
    ("sink","The Sink","Cable Car Bus","The Drop","hidden"),
    ("chapel-ward","Chapel Ward","Nave Node","The Well","public"),
    ("old-works","Old Works","Foundry Floor","Cut Cable","hidden"),
    ("terraces","Terraces","Block A Super","Basement Riser","gated"),
    ("sodium-row","Sodium Row","House Lights","Stage Door","hidden"),
    ("undercity","Undercity","Pumphouse Panel","The Seam","public"),
    ("scour","Scour","Landing Uplink","Static","gated"),
)
NOTABLE = {
    "spire": ("Pass Office","Executive Lift Bus","Skywatch Feed"),
    "core": ("Precinct Frontage","Tram Signal Bus","Civic Hall Annex","Bank Vestibule"),
    "vatside": ("Vatline Queue","Clinic Scheduler","Template Vault Approach"),
    "tramyard": ("Gate Bus West","Depot Floor","Convoy Staging","Dispatch Approach"),
    "sink": ("Terrace Wards","Floor Market","Sable's Back Room"),
    "chapel-ward": ("Bell Gallery","Listening Post Approach"),
    "old-works": ("Annex Records","Ninety-Nine's Drop","the Tape Room"),
    "terraces": ("Block B Super","Outpost Feed","Private-core register"),
    "sodium-row": ("Tin Halo Back Bar","Sign Grid"),
    "undercity": ("Cavern Relay","Outworks Seal Approach"),
    "scour": (),
}
SCOUR_LINKS = {
    "core":"Landing Uplink", "undercity":"Mile Relay", "old-works":"Beacon Relay",
    "tramyard":"Crash Relay", "spire":"Far Relay", "terraces":"Patrol Beacon",
}


def write(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(value,ensure_ascii=False,indent=2)+"\n",encoding="utf-8",newline="\n")


def build() -> None:
    source=WORLD.read_text(encoding="utf-8")
    table=source.split("## 2. Sectors",1)[1].split("Notes:",1)[0]
    counts={}
    for line in table.splitlines():
        parts=[part.strip() for part in line.split("|")]
        if len(parts)>4 and parts[2].isdigit():
            split=tuple(int(n) for n in re.findall(r"\d+",parts[3]))
            counts[parts[1]]=int(parts[2]),split
    sectors={}
    used: dict[str,set[int]]={}
    for slug,name,entry,descent,descent_access in DISTRICTS:
        total,split=counts[name]
        assert total==sum(split)
        sid="lat-"+slug
        cells=[]
        kinds=["public"]*split[0]+["gated"]*split[1]+["hidden"]*split[2]
        for i,kind in enumerate(kinds):
            cells.append({"id":f"{sid}-c{i+1:02}","kind":kind,"pos":[i%8,i//8],
                "neighbours":[],"label":f"Signal rack {i+1:02}",
                **({"requirement":"program:key:2"} if kind=="gated" else {})})
        positions={tuple(c["pos"]):c for c in cells}
        for cell in cells:
            x,y=cell["pos"]
            cell["neighbours"]=[positions[p]["id"] for p in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)) if p in positions]
        cells[0]["label"]=entry
        used[slug]={0}
        descent_i=max(i for i,kind in enumerate(kinds) if kind==descent_access)
        cells[descent_i].update(kind="descent",access=descent_access,label=descent)
        if slug=="scour":
            cells[descent_i]["requirement"]="event:ring-fall"
        used[slug].add(descent_i)
        sectors[slug]={"schema":1,"id":sid,"district":name,"entry":cells[0]["id"],"layout_size":[8,6],"cells":cells}

    def allocate(slug: str, access: str, label: str) -> dict:
        for i,cell in enumerate(sectors[slug]["cells"]):
            if i not in used[slug] and cell["kind"]==access:
                used[slug].add(i);cell["label"]=label
                return cell
        raise ValueError(f"{slug}: no spare {access} cell for {label}")

    def link(a: str, b: str) -> None:
        def endpoint(slug: str, other: str) -> dict:
            if slug=="scour" and other=="core":
                return sectors[slug]["cells"][0]
            label=SCOUR_LINKS[other] if slug=="scour" else sectors[other]["district"]+" uplink"
            return allocate(slug,"public",label)
        left,right=endpoint(a,b),endpoint(b,a)
        left["uplink"]={"sector":sectors[b]["id"],"cell":right["id"]}
        right["uplink"]={"sector":sectors[a]["id"],"cell":left["id"]}

    for slug,*_ in DISTRICTS:
        if slug!="core":link("core",slug)
    for slug in SCOUR_LINKS:
        if slug!="core":link("scour",slug)
    for slug,labels in NOTABLE.items():
        for label in labels:
            # Named facilities sit on visible routes; a core's own access is
            # a separate approach below, not an invented hardware object.
            try:allocate(slug,"public",label)
            except ValueError:allocate(slug,"gated",label)

    sections=re.split(r"(?m)^### 3\.(\d+) ([^\n]+)\n",source)
    for offset in range(1,len(sections),3):
        number=int(sections[offset])
        if not 1<=number<=11:continue
        slug=DISTRICTS[number-1][0]
        body=sections[offset+2]
        for label,cid in re.findall(r"\*\*([^*]+)\*\* \(`([^`]+)`\)",body):
            if cid in ("lat-private-core","lat-relay-uplink"):continue
            for name,planned in [(label,cid)]:
                access="public" if planned=="lat-wake-hall" else "hidden" if planned in ("lat-ninety-nines-drop","lat-site-zero-annex") else "gated"
                cell=allocate(slug,access,name+" entrance")
                cell.update(kind="core_entrance",access=access,core_placeholder=True,planned_core=planned)

    def district(zone: str) -> str:
        prefix=zone.split("-",1)[0]
        return {"spire":"spire","vatside":"vatside","tramyard":"tramyard",
                "sink":"sink","chapel":"chapel-ward","oldworks":"old-works",
                "terraces":"terraces","under":"undercity","scour":"scour"}[prefix]

    services=source.split("### 3.12",1)[1].split("### 3.13",1)[0]
    for line in services.splitlines():
        parts=[part.strip() for part in line.split("|")]
        if len(parts)>5 and parts[1].startswith("`lat-"):
            planned=parts[1].strip("`")
            zone=re.search(r"`([^`]+)`",parts[4]).group(1)
            cell=allocate(district(zone),"gated",parts[2]+" entrance")
            cell.update(kind="core_entrance",access="gated",core_placeholder=True,planned_core=planned)
    design=Path("docs/design/00-game-design.md").read_text(encoding="utf-8")
    schedule=design.split("### 7.7 Relay schedule",1)[1].split("Cable fare",1)[0]
    for line in schedule.splitlines():
        parts=[part.strip() for part in line.split("|")]
        if len(parts)>4 and parts[1].startswith("`"):
            key,name=parts[1].split(" / ",1)
            zone=parts[2].strip("`")
            cell=allocate(district(zone),"gated",name+" entrance")
            cell.update(kind="core_entrance",access="gated",core_placeholder=True,planned_core="lat-relay-"+key.strip("`"))
    for sector in sectors.values():
        write(ROOT/"sectors"/(sector["id"]+".json"),sector)
    (ROOT/"text/lattice-jackin.md").write_text(
        "The city goes quiet. Cells resolve under your feet.\n"
        "Your body stays upstairs. Its shelter still matters.\n"
        "Arrows follow links. J brings you back from a public cell.\n",
        encoding="utf-8",newline="\n")


if __name__=="__main__":
    build()
